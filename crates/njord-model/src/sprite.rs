//! Sprite names and sprite sheet entries (`Sprite` in `Colors.kt`, `IconInfo.kt`).

use serde::{Deserialize, Serialize};

use crate::string_enum;

/// One entry of a MapLibre sprite sheet index (`/v1/content/sprites/<theme>_simplified.json`).
///
/// The sheets are static files, so the optional stretch metadata is omitted when absent rather
/// than written as `null`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct IconInfo {
    pub width: i32,
    pub height: i32,
    pub x: i32,
    pub y: i32,
    pub pixel_ratio: i32,
    /// MapLibre stretchable-sprite metadata (sprites used with `icon-text-fit`), in this sheet's
    /// pixels.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stretch_x: Option<Vec<Vec<i32>>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub stretch_y: Option<Vec<Vec<i32>>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub content: Option<Vec<i32>>,
}

